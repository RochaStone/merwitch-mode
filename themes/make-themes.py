#!/usr/bin/env python3
"""make-themes.py (from the pink-terminal sibling kit, MIT): writes iTerm2, Ghostty and Warp themes from any style.json.

  python3 make-themes.py                       uses the style.json lookup (see STYLE.md)
  python3 make-themes.py --style my.json       a specific file
  python3 make-themes.py --out ~/Desktop       where to write (default: this folder)

Writes <slug>.itermcolors, <slug>.ghostty and <slug>.yaml, where slug comes from the style's name.
palette.hero is the GROUND (the background). Type is whichever of paper or ink reads better on it.
The ANSI accents come from your palette: accent (magenta), gold (yellow), cool (blue), wine (red),
plus mint for green, because terminals need a green and most brand palettes have none.
Every accent is lifted toward the type colour until it reads on the ground (3:1 contrast or better),
so error text in red is never invisible on a dark ground.
"""
import argparse
import os
import plistlib
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))  # the repo root
from merwitch_style import load_style, slug  # noqa: E402

MINT = "#8FD8B4"   # the mint pill colour of the Rocheverse look; used for the green slot


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexed(c):
    return "#%02X%02X%02X" % tuple(max(0, min(255, round(v))) for v in c)


def mix(a, b, t):
    """t of the way from colour a to colour b."""
    ra, rb = rgb(a), rgb(b)
    return hexed(x + (y - x) * t for x, y in zip(ra, rb))


def luminance(h):
    def lin(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(v) for v in rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def readable(colour, ground, toward, minimum=3.0):
    """The colour itself if it reads on the ground, else nudged toward `toward` until it does."""
    t = 0.0
    while contrast(colour if t == 0 else mix(colour, toward, t), ground) < minimum and t < 1:
        t = round(t + 0.05, 2)
    return colour if t == 0 else mix(colour, toward, t)


def scheme(p):
    bg = p["hero"]
    fg = p["paper"] if contrast(p["paper"], bg) >= contrast(p["ink"], bg) else p["ink"]
    lift = lambda c: readable(c, bg, fg)  # noqa: E731
    up = lambda c: readable(mix(c, fg, 0.25), bg, fg)  # noqa: E731
    wine = p.get("wine") or p["marker"]
    cyan = mix(MINT, p["cool"], 0.5)
    other = p["ink"] if fg == p["paper"] else p["paper"]
    ansi = [other, lift(wine), lift(MINT), lift(p["gold"]), lift(p["cool"]), lift(p["accent"]), lift(cyan), fg,
            readable(mix(bg, fg, 0.45), bg, fg), up(p["marker"]), up(MINT), up(p["gold"]),
            up(p["cool"]), up(p["accent"]), up(cyan), "#FFFFFF" if fg == p["paper"] else "#000000"]
    return {"bg": bg, "fg": fg, "cursor": p["accent"], "cursor_text": bg,
            "sel_bg": p.get("wine") or mix(bg, fg, 0.25), "sel_fg": fg, "bold": fg, "ansi": ansi}


def iterm(s):
    def comp(h):
        r, g, b = (v / 255 for v in rgb(h))
        return {"Alpha Component": 1.0, "Blue Component": b, "Color Space": "sRGB",
                "Green Component": g, "Red Component": r}
    d = {f"Ansi {i} Color": comp(c) for i, c in enumerate(s["ansi"])}
    d.update({"Background Color": comp(s["bg"]), "Foreground Color": comp(s["fg"]), "Bold Color": comp(s["bold"]),
              "Cursor Color": comp(s["cursor"]), "Cursor Text Color": comp(s["cursor_text"]),
              "Cursor Guide Color": comp(s["sel_bg"]), "Selection Color": comp(s["sel_bg"]),
              "Selected Text Color": comp(s["sel_fg"]), "Link Color": comp(s["cursor"]), "Badge Color": comp(s["cursor"])})
    return plistlib.dumps(d)


def ghostty(s, name, sl):
    lines = [f"# {name}: generated by make-themes.py from style.json. Ghostty theme.",
             "# Either paste these lines into ~/.config/ghostty/config,",
             f"# or save this file as ~/.config/ghostty/themes/{sl} and add: theme = {sl}",
             f"background = {s['bg']}", f"foreground = {s['fg']}", f"cursor-color = {s['cursor']}",
             f"cursor-text = {s['cursor_text']}", f"selection-background = {s['sel_bg']}",
             f"selection-foreground = {s['sel_fg']}"]
    lines += [f"palette = {i}={c}" for i, c in enumerate(s["ansi"])]
    return "\n".join(lines) + "\n"


def warp(s, name, sl):
    names = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
    safe = name.replace("'", "''")
    lines = [f"# {name}: generated by make-themes.py from style.json. Warp theme.",
             f"# Copy to ~/.warp/themes/{sl}.yaml, then pick it in Settings > Appearance > Themes.",
             f"name: '{safe}'", f"accent: '{s['cursor']}'", f"cursor: '{s['cursor']}'",
             f"background: '{s['bg']}'", f"foreground: '{s['fg']}'",
             f"details: {'lighter' if luminance(s['bg']) > 0.18 else 'darker'}", "terminal_colors:", "  normal:"]
    lines += [f"    {n}: '{s['ansi'][i]}'" for i, n in enumerate(names)]
    lines += ["  bright:"] + [f"    {n}: '{s['ansi'][i + 8]}'" for i, n in enumerate(names)]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--style", default="")
    ap.add_argument("--out", default=os.path.dirname(os.path.abspath(__file__)))
    args = ap.parse_args()
    style, used = load_style(args.style or None)
    name = style.get("name") or "My Style"
    sl = slug(name)
    s = scheme(style["palette"])
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, f"{sl}.itermcolors"), "wb") as fh:
        fh.write(iterm(s))
    with open(os.path.join(args.out, f"{sl}.ghostty"), "w", encoding="utf-8") as fh:
        fh.write(ghostty(s, name, sl))
    with open(os.path.join(args.out, f"{sl}.yaml"), "w", encoding="utf-8") as fh:
        fh.write(warp(s, name, sl))
    print(f"themes for '{name}' (from {used or 'built-in defaults'}) written to {args.out}: {sl}.itermcolors, {sl}.ghostty, {sl}.yaml")


if __name__ == "__main__":
    main()
