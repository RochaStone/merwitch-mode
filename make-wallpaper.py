#!/usr/bin/env python3
"""make-wallpaper.py (from the pink-terminal sibling kit, MIT): writes the wallpaper SVG from any style.json, in any of three motifs.

  python3 make-wallpaper.py                          style.json lookup (see STYLE.md), its motif
  python3 make-wallpaper.py --motif cyberpunk        analog | cyberpunk | y2k-blog
  python3 make-wallpaper.py --style my.json --out ~/Desktop/wall.svg

One set of data, three structures:
  analog     THE newsprint front page on a desk: masthead, dateline, washi tape, a stamp.
  cyberpunk  a plum CRT in a cyberdeck bezel: prompt line, scanlines, block progress, candy cursor.
  y2k-blog   a 2003 blog window: title bar, sidebar, mood, marquee, hit counter, pixel hearts.
Palette and fonts set the colour and type. The motif sets the structure.
"""
import argparse
import os
import sys
from datetime import date
from urllib.parse import quote_plus
from xml.sax.saxutils import escape

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from merwitch_style import PIXEL_FONT, PLACEHOLDER, load_style, motif_of, slug  # noqa: E402

W, H = 2560, 1600
AXES = {"Fraunces": ":ital,opsz,wght@0,9..144,400;0,9..144,900;1,9..144,400",
        "Bricolage Grotesque": ":opsz,wght@12..96,400;12..96,800", "DM Mono": ":wght@400;500"}
HEART = ["0110110", "1111111", "1111111", "0111110", "0011100", "0001000"]
STAR = ["0001000", "0001000", "1111111", "0111110", "0110110", "1000001"]
SIGNATURE = {"analog": "VOL. 1 · NO. 001", "cyberpunk": ":~$", "y2k-blog": "you are visitor no. 000,777"}


def split_lines(text, max_lines=3):
    """Balanced split into 1 to 3 lines, picking the split that allows the largest type."""
    words = text.split()
    best = ([text], len(text))
    for n in range(2, min(max_lines, len(words)) + 1):
        target = len(text) / n
        lines, cur = [], ""
        for w in words:
            if cur and len(cur) + 1 + len(w) > target + 3 and len(lines) < n - 1:
                lines.append(cur)
                cur = w
            else:
                cur = f"{cur} {w}".strip()
        lines.append(cur)
        longest = max(len(x) for x in lines)
        if longest < best[1]:
            best = (lines, longest)
    return best[0]


def pixels(grid, x, y, cell, fill):
    """A pixel-art shape from a grid of 0 and 1, as plain rects. No filters, no glow."""
    return "".join(f'<rect x="{x + c * cell:.0f}" y="{y + r * cell:.0f}" width="{cell}" height="{cell}" fill="{fill}"/>'
                   for r, row in enumerate(grid) for c, v in enumerate(row) if v == "1")


def headline_block(lines, cx, top, max_w, max_h, cls, fill, width_factor=0.70):
    size = int(min(250, max_w / (width_factor * max(len(x) for x in lines)), max_h / len(lines)))
    out = "\n".join(f'  <text x="{cx}" y="{top + size * 0.82 + i * size:.0f}" text-anchor="middle" class="{cls}" '
                    f'font-size="{size}" fill="{fill}">{escape(t)}</text>' for i, t in enumerate(lines))
    return out, top + size * len(lines)


def data(style, today=None):
    """Everything the three skins need, worked out once."""
    p, f, ln = style["palette"], style.get("fonts", {}), style.get("lines", {})
    fonts = {"mast": f.get("masthead") or "Fraunces", "label": f.get("label") or "Bricolage Grotesque",
             "scrawl": f.get("scrawl") or "Permanent Marker", "mono": f.get("mono") or "DM Mono", "pixel": PIXEL_FONT}
    name = style.get("name") or ""
    world = (ln.get("magazine") or (slug(name) if name else "my-world")).lower().replace(" ", "-")
    headline = ln.get("headline") or PLACEHOLDER
    return {
        "ground": p["hero"], "paper": p["paper"], "blush": p.get("paper_pink") or p["paper"], "ink": p["ink"],
        "accent": p["accent"], "gold": p["gold"], "wine": p.get("wine") or p["plum"], "marker": p["marker"],
        "fonts": fonts, "headline": headline, "lines": split_lines(headline.upper()),
        "masthead": (ln.get("masthead") or "").upper(), "scrawl": ln.get("scrawl") or "",
        "stamp": (ln.get("stamp") or "").upper(), "affirm": ln.get("affirm") or "",
        "owner": style.get("owner") or "", "world": world, "today": (today or date.today().strftime("%d %b %Y")).upper(),
    }


def head(d, extra_defs=""):
    fams = dict.fromkeys(d["fonts"].values())
    families = "&amp;".join(f"family={quote_plus(n)}{AXES.get(n, '')}" for n in fams) + "&amp;family=Pixelify+Sans"
    fo = {k: escape(v) for k, v in d["fonts"].items()}
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
  <title>{escape(d["headline"])}</title>
  <!-- Generated by make-wallpaper.py from style.json. Edit your style.json, not this file. -->
  <defs>
    <style>
      @import url('https://fonts.googleapis.com/css2?{families}&amp;display=block');
      .mast {{ font-family: '{fo["mast"]}', Georgia, serif; font-weight: 900; }}
      .serif {{ font-family: '{fo["mast"]}', Georgia, serif; }}
      .label {{ font-family: '{fo["label"]}', 'Helvetica Neue', Arial, sans-serif; font-weight: 800; }}
      .scrawl {{ font-family: '{fo["scrawl"]}', 'Marker Felt', cursive; }}
      .mono {{ font-family: '{fo["mono"]}', Menlo, monospace; }}
      .pixel {{ font-family: '{fo["pixel"]}', 'Pixelify Sans', Menlo, monospace; }}
    </style>
    <filter id="grain" x="0" y="0" width="100%" height="100%">
      <feTurbulence type="fractalNoise" baseFrequency="0.85" numOctaves="3" stitchTiles="stitch"/>
      <feColorMatrix type="matrix" values="0 0 0 0 0.2  0 0 0 0 0.05  0 0 0 0 0.15  0 0 0 0.06 0"/>
    </filter>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="125%">
      <feDropShadow dx="0" dy="26" stdDeviation="26" flood-color="#000000" flood-opacity="0.45"/>
    </filter>
{extra_defs}  </defs>
'''


def stamp_svg(d, x, y, colour, angle=8, cls="mast"):
    if not d["stamp"]:
        return ""
    w = 110 + 64 * len(d["stamp"])
    return (f'  <g transform="translate({x} {y}) rotate({angle})">'
            f'<rect x="{-w / 2:.0f}" y="-74" width="{w}" height="128" rx="6" fill="none" stroke="{colour}" stroke-width="5"/>'
            f'<rect x="{-w / 2 + 12:.0f}" y="-62" width="{w - 24}" height="104" rx="3" fill="none" stroke="{colour}" stroke-width="1.5"/>'
            f'<text x="0" y="14" text-anchor="middle" class="{cls}" font-size="78" fill="{colour}" letter-spacing="10">{escape(d["stamp"])}</text></g>\n')


def analog(d):
    """Newsprint front page on a desk."""
    sx, sy, sw, sh = 300, 170, 1960, 1260
    out = head(d) + f'  <rect width="{W}" height="{H}" fill="{d["ground"]}"/>\n'
    out += f'  <g transform="rotate(-1.4 1280 800)">\n  <rect x="{sx}" y="{sy}" width="{sw}" height="{sh}" fill="{d["paper"]}" filter="url(#shadow)"/>\n'
    if d["masthead"]:
        out += f'  <text x="1280" y="{sy + 190}" text-anchor="middle" class="mast" font-size="150" fill="{d["ink"]}">{escape(d["masthead"])}</text>\n'
    y = sy + 240
    out += (f'  <line x1="{sx + 80}" y1="{y}" x2="{sx + sw - 80}" y2="{y}" stroke="{d["ink"]}" stroke-width="5"/>\n'
            f'  <text x="{sx + 90}" y="{y + 44}" class="mono" font-size="30" letter-spacing="3" fill="{d["ink"]}">{SIGNATURE["analog"]}</text>\n'
            f'  <text x="{sx + sw - 90}" y="{y + 44}" text-anchor="end" class="mono" font-size="30" letter-spacing="3" fill="{d["ink"]}">{d["today"]}</text>\n'
            f'  <line x1="{sx + 80}" y1="{y + 66}" x2="{sx + sw - 80}" y2="{y + 66}" stroke="{d["ink"]}" stroke-width="1.5"/>\n')
    block, bottom = headline_block(d["lines"], 1280, y + 110, sw - 260, 640, "mast", d["ink"])
    out += block + "\n"
    if d["affirm"]:
        out += f'  <text x="1280" y="{bottom + 70:.0f}" text-anchor="middle" class="serif" font-style="italic" font-size="52" fill="{d["ink"]}">{escape(d["affirm"].lower())}</text>\n'
    if d["scrawl"]:
        out += (f'  <g transform="translate({sx + 120} {sy + sh - 90}) rotate(-4)"><text class="scrawl" font-size="70" fill="{d["marker"]}">{escape(d["scrawl"])}</text>'
                f'<path d="M-10,26 C220,52 640,46 900,18" stroke="{d["marker"]}" stroke-width="6" fill="none" stroke-linecap="round"/></g>\n')
    out += stamp_svg(d, sx + sw - 260, sy + sh - 150, d["wine"])
    for tx, ty, a in ((sx - 40, sy - 20, -32), (sx + sw - 210, sy - 30, 28)):   # washi tape, candy, half see-through
        out += f'  <rect x="{tx}" y="{ty}" width="260" height="70" fill="{d["accent"]}" opacity="0.72" transform="rotate({a} {tx + 130} {ty + 35})"/>\n'
    return out + f'  </g>\n  <rect width="{W}" height="{H}" filter="url(#grain)"/>\n</svg>\n'


def cyberpunk(d):
    """A plum CRT in a cyberdeck bezel. Soft scanlines, no glow, no flicker."""
    lines_pattern = (f'    <pattern id="scan" width="8" height="8" patternUnits="userSpaceOnUse">'
                     f'<rect width="8" height="2" fill="{d["paper"]}" opacity="0.045"/></pattern>\n')
    bezel = "#000000"
    out = head(d, lines_pattern) + f'  <rect width="{W}" height="{H}" fill="{d["ground"]}"/>\n'
    out += (f'  <rect x="90" y="90" width="2380" height="1420" rx="70" fill="{d["wine"]}" filter="url(#shadow)"/>\n'
            f'  <rect x="90" y="90" width="2380" height="1420" rx="70" fill="{bezel}" opacity="0.18"/>\n'
            f'  <rect x="190" y="180" width="2180" height="1180" rx="46" fill="{d["ground"]}"/>\n'
            f'  <rect x="190" y="180" width="2180" height="1180" rx="46" fill="url(#scan)"/>\n')
    for x, y in ((140, 140), (2420, 140), (140, 1460), (2420, 1460)):                    # gold screws
        out += f'  <circle cx="{x}" cy="{y}" r="16" fill="{d["gold"]}"/><line x1="{x - 9}" y1="{y}" x2="{x + 9}" y2="{y}" stroke="{d["ground"]}" stroke-width="4"/>\n'
    prompt = f'{d["world"]}{SIGNATURE["cyberpunk"]} ./{slug(d["scrawl"]) if d["scrawl"] else "start"}'
    out += f'  <text x="300" y="330" class="mono" font-size="44" fill="{d["paper"]}">{escape(prompt)}</text>\n'
    block, bottom = headline_block(d["lines"], 1280, 420, 1900, 560, "label", d["paper"], 0.66)
    out += block + "\n"
    out += f'  <rect x="{300 + len(prompt) * 26.5 + 14:.0f}" y="292" width="26" height="48" fill="{d["accent"]}"/>\n'   # the candy block cursor
    if d["stamp"]:                                                                          # block progress bar
        out += f'  <text x="300" y="{bottom + 130:.0f}" class="pixel" font-size="40" fill="{d["gold"]}">{escape(d["stamp"])}</text>\n'
        for i in range(12):
            out += f'  <rect x="{560 + i * 70}" y="{bottom + 92:.0f}" width="56" height="44" fill="{d["gold"] if i < 9 else "none"}" stroke="{d["gold"]}" stroke-width="3"/>\n'
        out += f'  <text x="1420" y="{bottom + 130:.0f}" class="pixel" font-size="40" fill="{d["gold"]}">75%</text>\n'
    if d["affirm"]:
        out += f'  <text x="300" y="1270" class="mono" font-size="36" fill="{d["accent"]}">&gt; {escape(d["affirm"].lower())}</text>\n'
    for i, (label, colour) in enumerate((("PWR", d["accent"]), ("RDY", d["gold"]))):     # status LEDs
        out += (f'  <circle cx="{1960 + i * 220}" cy="1440" r="14" fill="{colour}"/>'
                f'<text x="{1990 + i * 220}" y="1453" class="pixel" font-size="34" fill="{d["paper"]}">{label}</text>\n')
    out += pixels(["0100010", "0111110", "1101011", "1111111", "0111110"], 300, 1405, 10, d["gold"]) + "\n"   # pixel leopard
    return out + "</svg>\n"


def y2k_blog(d):
    """A 2003 blog page in a window: title bar, sidebar, mood, marquee, hit counter."""
    clip = f'    <clipPath id="win"><rect x="220" y="150" width="2120" height="1300"/></clipPath>\n'
    tile = clip + (f'    <pattern id="tile" width="120" height="120" patternUnits="userSpaceOnUse">'
            f'<rect width="120" height="120" fill="{d["blush"]}"/>{pixels(HEART, 40, 44, 6, d["accent"])}</pattern>\n')
    out = head(d, tile) + f'  <rect width="{W}" height="{H}" fill="url(#tile)"/>\n'
    wx, wy, ww, wh = 220, 150, 2120, 1300
    title = f'{d["world"]}.exe'
    out += (f'  <rect x="{wx}" y="{wy}" width="{ww}" height="{wh}" fill="{d["paper"]}" stroke="{d["ground"]}" stroke-width="6" filter="url(#shadow)"/>\n'
            f'  <rect x="{wx}" y="{wy}" width="{ww}" height="84" fill="{d["ground"]}"/>\n'
            f'  <text x="{wx + 40}" y="{wy + 56}" class="pixel" font-size="40" fill="{d["paper"]}">{escape(title)}</text>\n')
    for i in range(3):                                                                      # three gold buttons
        out += f'  <rect x="{wx + ww - 210 + i * 64}" y="{wy + 22}" width="44" height="40" fill="{d["gold"]}" stroke="{d["ink"]}" stroke-width="3"/>\n'
    mx, mw = wx + 60, 1360
    block, bottom = headline_block(d["lines"], mx + mw / 2, wy + 170, mw - 60, 600, "mast", d["ink"])
    out += block + "\n"
    if d["affirm"]:
        out += f'  <text x="{mx + mw / 2:.0f}" y="{bottom + 70:.0f}" text-anchor="middle" class="serif" font-style="italic" font-size="50" fill="{d["ink"]}">{escape(d["affirm"].lower())}</text>\n'
    if d["scrawl"]:                                                                         # the marquee line
        band = (" ✧ " + d["scrawl"]) * 4
        out += (f'  <rect x="{wx}" y="{wy + wh - 210}" width="{ww}" height="74" fill="{d["wine"]}"/>\n'
                f'  <text x="{wx + 30}" y="{wy + wh - 160}" class="mono" font-size="38" fill="{d["paper"]}" clip-path="url(#win)">{escape(band.strip())}</text>\n')
    out += f'  <text x="{wx + 60}" y="{wy + wh - 60}" class="mono" font-size="30" fill="{d["ink"]}">last updated {d["today"].lower()}</text>\n'
    sx, sy, sw = wx + ww - 620, wy + 140, 560                                               # the sidebar
    boxes = [("about me", escape(d["owner"].lower()) if d["owner"] else "&#160;"), ("mood", "✧"),
             ("guestbook", "sign my guestbook ✧")]
    for i, (label, value) in enumerate(boxes):
        y = sy + i * 230
        out += (f'  <rect x="{sx}" y="{y}" width="{sw}" height="190" fill="{d["blush"]}" stroke="{d["ground"]}" stroke-width="4"/>\n'
                f'  <rect x="{sx}" y="{y}" width="{sw}" height="54" fill="{d["ground"]}"/>\n'
                f'  <text x="{sx + 24}" y="{y + 38}" class="pixel" font-size="30" fill="{d["paper"]}">{label}</text>\n'
                f'  <text x="{sx + 24}" y="{y + 130}" class="label" font-size="46" fill="{d["ink"]}">{value}</text>\n')
    out += f'  <text x="{sx}" y="{sy + 730}" class="mono" font-size="34" fill="{d["ink"]}">{SIGNATURE["y2k-blog"]}</text>\n'
    out += stamp_svg(d, sx + 280, sy + 850, d["wine"], angle=-6, cls="pixel")
    for x, y, shape in ((wx - 70, wy + 260, HEART), (wx + ww + 10, wy + 900, STAR), (wx + 880, wy - 70, STAR)):
        out += pixels(shape, x, y, 12, d["gold"]) + "\n"                                    # gold pixel stickers
    return out + "</svg>\n"


SKINS = {"analog": analog, "cyberpunk": cyberpunk, "y2k-blog": y2k_blog}


def build(style, motif=None, today=None):
    return SKINS[motif_of(motif or style.get("motif"))](data(style, today))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--style", default="")
    ap.add_argument("--motif", default="", help="analog, cyberpunk or y2k-blog (default: your style.json motif)")
    ap.add_argument("--out", default="wallpaper.svg")
    ap.add_argument("--date", default="", help='the printed date, like "27 Oct 2026" (default: today)')
    ap.add_argument("--png", default="", help="also render a PNG here, like ~/Pictures/merwitch.png (needs Chrome)")
    ap.add_argument("--size", default="2560x1600", help="PNG size, WIDTHxHEIGHT (default 2560x1600)")
    args = ap.parse_args()
    style, used = load_style(args.style or None)
    motif = motif_of(args.motif or style.get("motif"))
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(build(style, motif, args.date or None))
    print(f"{motif} wallpaper for '{style.get('name') or 'my style'}' (from {used or 'built-in defaults'}) written to {args.out}")
    if args.png:
        import render
        try:
            w, h = (int(x) for x in args.size.lower().split("x"))
        except ValueError:
            print("the size needs to look like 2560x1600", file=sys.stderr)
            return 2
        ok, msg = render.svg_to_png(args.out, os.path.expanduser(args.png), w, h, style["palette"]["hero"])
        print(msg)
        return 0 if ok else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
